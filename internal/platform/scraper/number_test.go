package scraper

import "testing"

func TestParseCount(t *testing.T) {
	tests := []struct {
		in   string
		want int
	}{
		// 纯数字
		{"123", 123},
		{"10", 10},
		{"0", 0},
		{"", 0},
		{"–", 0},
		{"abc", 0},
		// 千分位分隔
		{"1,234", 1234},
		{"1,234,567", 1234567},
		{"1 234", 1234},
		{"1\u00a0234", 1234},
		{"1 093", 1093},
		// 欧洲/越南点号千分位
		{"1.314", 1314},
		{"1.314.567", 1314567},
		// 英文缩写(千位)
		{"1.04K", 1040},
		{"1.04k", 1040},
		{"12.5K", 12500},
		{"1,2K", 1200},
		{"1,5K", 1500},
		{"1.005K", 1005},
		// 英文缩写(百万/十亿)
		{"1.2M", 1200000},
		{"1.2m", 1200000},
		{"3B", 3000000000},
		// 中文计数
		{"1.2万", 12000},
		{"12.5万", 125000},
		{"1.2萬", 12000},
		{"2.5亿", 250000000},
		{"1.5億", 150000000},
		{"3千", 3000},
		// 带单位/前后缀文本
		{"1.5K views", 1500},
		{"12.5万 位订阅者", 125000},
		{"  7.7万", 77000},
		// 英文单词数量级
		{"1.04 thousand subscribers", 1040},
		{"1.04 thousand", 1040},
		{"1.04 thousands", 1040},
		{"1.2 million", 1200000},
		{"1.2 million subscribers", 1200000},
		{"3 billion", 3000000000},
		{"2 hundred", 200},
		// 组合: 欧洲小数 + 后缀
		{"1.234,5K", 1234500},
	}

	for _, tt := range tests {
		if got := ParseCount(tt.in); got != tt.want {
			t.Errorf("ParseCount(%q) = %d, want %d", tt.in, got, tt.want)
		}
	}
}
